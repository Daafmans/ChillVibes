// Generates game/projects.js from the tree in docs/06-projects.md. Usage: node tools/build-projects.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const lines = fs.readFileSync(path.join(root, 'docs', '06-projects.md'), 'utf8').split(/\r?\n/);
const start = lines.findIndex(l => /^## Tree\s*$/.test(l));
if (start < 0) throw new Error('docs/06-projects.md has no "## Tree" section');

const projects = [];
const stack = [];            // stack[depth] = id of the latest project at that depth
let cat = null;
for (const raw of lines.slice(start + 1)) {
  const h = raw.match(/^###\s+(.+?)\s*$/);
  if (h) { cat = h[1]; stack.length = 0; continue; }
  if (/^## /.test(raw)) break;
  const m = raw.match(/^(\s*)- (.+)$/);
  if (!m) continue;
  const where = `"${raw.trim().slice(0, 40)}"`;
  if (!cat) throw new Error(`${where}: project before any ### category heading`);
  const indent = m[1].replace(/\t/g, '  ').length;
  if (indent % 2) throw new Error(`${where}: indent with 2 spaces per level`);
  const depth = indent / 2;
  if (depth > stack.length) throw new Error(`${where}: indented more than one level below its parent`);
  const f = m[2].split('|').map(s => s.trim());
  if (f.length !== 4) throw new Error(`${where}: expected "id | Name | Effect | Repeatable"`);
  const [id, name, desc, rep] = f;
  if (!/^[a-z]+$/.test(id)) throw new Error(`${where}: id must be lowercase letters`);
  if (projects.some(p => p.id === id)) throw new Error(`${where}: duplicate id`);
  if (!/^(yes|no)$/i.test(rep)) throw new Error(`${where}: repeatable must be yes or no`);
  stack.length = depth;
  projects.push({ id, cat, name, parent: depth ? stack[depth - 1] : null, multi: /^yes$/i.test(rep), desc: desc.replace(/\*\*/g, '') });
  stack[depth] = id;
}
if (!projects.length) throw new Error('no projects found');

const out = `// GENERATED by tools/build-projects.js from docs/06-projects.md. Do not edit by hand.
(function (CV) {
  CV.PROJECTS.push(
${projects.map(p => '    ' + JSON.stringify(p)).join(',\n')}
  );
})(globalThis.CV);
`;
fs.writeFileSync(path.join(root, 'game', 'projects.js'), out);
console.log(`Wrote game/projects.js (${projects.length} projects)`);
